/**
 * Generate responsive WebP variants + a Vite-friendly import module.
 * Run: `npm run optimize:images`
 *
 * Reads JPGs from `src/assets/Evolve Images/` and writes:
 * - `src/assets/magazine-optimized/img-{n}-{w}.webp`
 * - `src/assets/magazinePhotos.generated.js`
 */
import { readdirSync, mkdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const __dir = dirname(fileURLToPath(import.meta.url));
const root = join(__dir, "..");
const srcDir = join(root, "src/assets/Evolve Images");
const outDir = join(root, "src/assets/magazine-optimized");
const outModule = join(root, "src/assets/magazinePhotos.generated.js");

/** Output widths (px). Largest becomes default `src`. */
const WIDTHS = [640, 1280, 1920];
const WEBP_QUALITY = 78;

mkdirSync(outDir, { recursive: true });

const jpgFiles = readdirSync(srcDir)
  .filter((f) => /^evolve gym magazine .+images-(\d+)\.jpg$/i.test(f))
  .map((f) => {
    const m = f.match(/images-(\d+)\.jpg$/i);
    return { file: f, index: Number(m[1]) };
  })
  .sort((a, b) => a.index - b.index);

if (jpgFiles.length === 0) {
  console.error("[optimize:images] No magazine JPGs found in", srcDir);
  process.exit(1);
}

/** @type {Array<{ index: number; width: number; height: number; imports: Record<number, string> }>} */
const photos = [];

for (const { file, index } of jpgFiles) {
  const input = join(srcDir, file);
  const meta = await sharp(input).metadata();
  const baseW = meta.width || 2560;
  const baseH = meta.height || 1706;
  /** @type {Record<number, string>} */
  const imports = {};

  for (const w of WIDTHS) {
    const targetW = Math.min(w, baseW);
    const outName = `img-${index}-${w}.webp`;
    const outPath = join(outDir, outName);
    await sharp(input)
      .rotate()
      .resize({ width: targetW, withoutEnlargement: true })
      .webp({ quality: WEBP_QUALITY, effort: 4 })
      .toFile(outPath);
    imports[w] = outName;
    console.log(`[optimize:images] wrote ${outName}`);
  }

  const largest = WIDTHS[WIDTHS.length - 1];
  const scale = Math.min(largest, baseW) / baseW;
  photos.push({
    index,
    width: Math.round(baseW * scale),
    height: Math.round(baseH * scale),
    imports,
  });
}

const importLines = [];
const photoBlocks = [];

for (const photo of photos) {
  const varNames = {};
  for (const w of WIDTHS) {
    const varName = `img${photo.index}_${w}`;
    varNames[w] = varName;
    importLines.push(
      `import ${varName} from "./magazine-optimized/${photo.imports[w]}";`
    );
  }
  const srcSetParts = WIDTHS.map((w) => `\${${varNames[w]}} ${w}w`).join(", ");
  photoBlocks.push(`  {
    src: ${varNames[WIDTHS[WIDTHS.length - 1]]},
    srcSet: \`${srcSetParts}\`,
    width: ${photo.width},
    height: ${photo.height},
  }`);
}

const moduleSource = `/**
 * AUTO-GENERATED by scripts/optimize-magazine-images.mjs — do not edit by hand.
 * Re-run: npm run optimize:images
 */

${importLines.join("\n")}

/** @typedef {{ src: string; srcSet: string; width: number; height: number }} EvolvePhoto */

/** @type {readonly EvolvePhoto[]} */
export const magazinePhotos = [
${photoBlocks.join(",\n")}
];
`;

writeFileSync(outModule, moduleSource, "utf8");
console.log(
  `[optimize:images] wrote ${outModule} (${photos.length} photos × ${WIDTHS.length} sizes)`
);
